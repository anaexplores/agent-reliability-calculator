"""Q5 replication on Terminal-Bench 2.0: convert tb_trials.csv (TB 2.0) to the tb40_trials.csv format.
The selection rule was fixed before the analysis.

Configuration = agent x model; only configurations with >=5 trials on every task (allowing one
missing task); the first 5 trials per task in file order; tasks = those common to all kept
configurations.

Input: tb_trials.csv (TB 2.0 trials, regenerated by measurement/fetch_terminalbench.mjs).
Output: tb20_q5_trials.csv (columns model, task, reward) for measurement/analyze_icc_heterogeneity_q5.py,
plus a console summary of pass@1 per kept configuration.
Backs docs/measurements/08_defects_and_icc_tb40.md.

    python measurement/prep_tb20_for_q5.py tb_trials.csv tb20_q5_trials.csv
"""
import sys, csv
from collections import defaultdict

sys.stdout.reconfigure(encoding='utf-8')
src, dst = sys.argv[1], sys.argv[2]
S = defaultdict(lambda: defaultdict(list))
tasks = set()
for r in csv.DictReader(open(src, encoding='utf-8')):
    S[f"{r['agent']} | {r['model']}"][r['task_name']].append(r['reward'])
    tasks.add(r['task_name'])
full5 = {c: {t for t, v in S[c].items() if len(v) >= 5} for c in S}
keep = [c for c in sorted(S) if len(full5[c]) >= len(tasks) - 1]  # selection fix: ≥88 of 89
tasks = set.intersection(*(full5[c] for c in keep))
print(f'configs total {len(S)}; eligible {len(keep)}; common tasks {len(tasks)}')
with open(dst, 'w', newline='', encoding='utf-8') as f:
    w = csv.writer(f); w.writerow(['model', 'task', 'reward'])
    for c in keep:
        for t in sorted(tasks):
            for x in S[c][t][:5]:
                w.writerow([c, t, x])
for c in keep:
    v = [float(x or 0) >= 1 for t in tasks for x in S[c][t][:5]]
    print(f'  {sum(v)/len(v):.3f}  {c}')
