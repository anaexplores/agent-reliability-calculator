# Reward hacking as a mechanism of retry correlation: does excluding tasks flagged for reward hacking
# lower the retry ICC on Terminal-Bench 2.0? Hypotheses and criteria were fixed before the analysis.
# Backs docs/measurements/07_reward_hacking.md.
#
# Computes the change in ICC(1) when the flagged tasks are excluded (main test: 33 tasks flagged in
# TB 2.1 submissions; S1: tasks flagged in >= 2 submissions; S2: flagged tasks minus the ones fixed in
# TB 2.1, with the null drawn from unfixed tasks; S3: ICC inside each subset), with a task bootstrap CI
# and a null that drops random tasks matched by success-rate quintile.
# ICC(1) with k0 is the same formula as in analyze_v4_benchmark_defects.mjs, but vectorized:
# all sums are linear in the task multiplicities, so the bootstrap is a matrix multiplication.
#
# Inputs (opened relative to the current directory): tb_trials.csv (TB 2.0 trials, regenerated by
# measurement/fetch_terminalbench.mjs), tb21_reward_hacking_tasks.csv, tb21_fixed_tasks.txt.
# Output: h17_result.json (current directory) and a console summary.
# Usage (input files are opened by relative path, so run from the directory that holds all three;
# the two tb21_* files ship in measurement/):
#   python measurement/analyze_h17_reward_hacking.py
import csv, json, collections, sys
import numpy as np

sys.stdout.reconfigure(encoding='utf-8')

rng = np.random.default_rng(20260930)
B_BOOT, B_NULL = 2000, 5000

cells = collections.defaultdict(list)
for r in csv.DictReader(open('tb_trials.csv', encoding='utf-8')):
    if r['reward'] in ('0', '1'):
        cells[(r['task_name'], r['agent'], r['model'])].append(int(r['reward']))
cells = {k: v for k, v in cells.items() if len(v) >= 3}

tasks = sorted({k[0] for k in cells})
T = len(tasks); ti = {t: i for i, t in enumerate(tasks)}
# per task: n cells, N runs, S successes, Σk², Σs²/k, SSW
F = np.zeros((T, 6))
for (t, _, _), v in cells.items():
    k, s = len(v), sum(v)
    F[ti[t]] += [1, k, s, k * k, s * s / k, s - s * s / k]
task_p = F[:, 2] / F[:, 1]

def icc_w(w):
    """ICC for task weights w (shape (..., T)): 1 = task included once."""
    n, N, S, K2, A, W = (w @ F).T if w.ndim == 1 else np.moveaxis(w @ F, -1, 0)
    ssb = A - S * S / N
    dfw = N - n
    msb, msw = ssb / (n - 1), W / dfw
    k0 = (N - K2 / N) / (n - 1)
    return (msb - msw) / (msb + (k0 - 1) * msw)

hack = {r['task']: int(r['n_submissions']) for r in csv.DictReader(open('tb21_reward_hacking_tasks.csv', encoding='utf-8'))}
fixed = {l.strip() for l in open('tb21_fixed_tasks.txt', encoding='utf-8') if l.strip() and not l.startswith('#')}
mask = lambda names: np.array([t in names for t in tasks])
H33, H19 = mask(set(hack)), mask({t for t, s in hack.items() if s >= 2})
FIX = mask(fixed)
ONES = np.ones(T)
quint = np.searchsorted(np.quantile(task_p, [.2, .4, .6, .8]), task_p, side='right')

def delta(excl, universe=None):
    u = ONES if universe is None else universe.astype(float)
    return icc_w(u) - icc_w(u * ~excl)

def boot(excl, universe=None):
    u = ONES if universe is None else universe.astype(float)
    idx = np.flatnonzero(u)
    counts = np.zeros((B_BOOT, T))
    draws = rng.choice(idx, size=(B_BOOT, idx.size))
    for b in range(B_BOOT):
        counts[b] = np.bincount(draws[b], minlength=T)
    d = icc_w(counts) - icc_w(counts * ~excl)
    return np.nanpercentile(d, [2.5, 97.5])

def null(excl, universe=None):
    u = np.ones(T, bool) if universe is None else universe
    pool = {q: np.flatnonzero((quint == q) & u) for q in range(5)}
    need = {q: int(((quint == q) & excl & u).sum()) for q in range(5)}
    w = np.tile(u.astype(float), (B_NULL, 1))
    for b in range(B_NULL):
        for q in range(5):
            if need[q]:
                w[b, rng.choice(pool[q], need[q], replace=False)] = 0
    return icc_w(u.astype(float)) - icc_w(w)

def test(label, excl, universe=None):
    d = delta(excl, universe); lo, hi = boot(excl, universe); nd = null(excl, universe)
    p = (1 + (nd >= d).sum()) / (1 + nd.size)
    ok = d > 0 and lo > 0 and p < 0.05
    print(f'\n=== {label} === excluded {int((excl & (ONES.astype(bool) if universe is None else universe)).sum())} tasks')
    print(f'Δ = {d:+.4f}   95% bootstrap [{lo:+.4f}, {hi:+.4f}]')
    print(f'null (matched by success quintile): median {np.median(nd):+.4f}, 95th pct. {np.percentile(nd, 95):+.4f}, p = {p:.4f}')
    print('H1' if ok else 'H0 / not confirmed')
    return dict(delta=d, boot=[lo, hi], null_median=float(np.median(nd)), null_p95=float(np.percentile(nd, 95)), p=p, h1=bool(ok))

print(f'tasks {T}, cells {len(cells)}, runs {int(F[:,1].sum())}, ICC(all) = {icc_w(ONES):.4f}')
print(f'success quintiles of H33: {np.bincount(quint[H33], minlength=5).tolist()}  mean success H33 {task_p[H33].mean():.3f} vs rest {task_p[~H33].mean():.3f}')
res = {'main_H33': test('MAIN: H33', H33),
       'S1_H19': test('S1: H19 (labels in ≥2 submissions)', H19),
       'S2_H33_unfixed': test('S2: H33 without fixed tasks, null from unfixed tasks', H33 & ~FIX, ~FIX)}
s3 = dict(icc_hack=float(icc_w(H33.astype(float))), icc_rest=float(icc_w((~H33).astype(float))),
          icc_hack_unfixed=float(icc_w((H33 & ~FIX).astype(float))), icc_rest_unfixed=float(icc_w((~H33 & ~FIX).astype(float))))
print('\n=== S3: ICC within subsets ===')
for k, v in s3.items(): print(f'{k}: {v:.4f}')
res['S3'] = s3
json.dump(res, open('h17_result.json', 'w'), indent=1, default=float)
