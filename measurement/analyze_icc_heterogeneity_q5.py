"""Q5: is the retry ICC a property of the "model x harness" configuration, or noise?

Statistic V = variance of the ICC (ANOVA) across configurations. Null: each configuration keeps its
own pass@1, with a common ICC; π_t ~ Beta(mean=pass@1, ICC), 5 attempts Bernoulli(π_t), 66 tasks
(the task count is taken from the input file). Main test uses the mean ICC as the common value;
robustness checks use the median, and drop configurations with pass@1 < 0.13.
Hypotheses and criteria were fixed before the analysis.

Input: a trials CSV with columns model, task, reward and 5 attempts per task: tb40_trials.csv
(Terminal-Bench 4.0, regenerated by measurement/fetch_tb40_trials.py) or tb20_q5_trials.csv
(Terminal-Bench 2.0 replication, produced by measurement/prep_tb20_for_q5.py). Output: JSON on stdout
(icc_heterogeneity_q5.json, icc_heterogeneity_q5_tb20.json).
Backs docs/measurements/08_defects_and_icc_tb40.md.

    python measurement/analyze_icc_heterogeneity_q5.py tb40_trials.csv > measurement/icc_heterogeneity_q5.json
"""
import sys, csv, json, random
from collections import defaultdict
from statistics import mean, median, pvariance

sys.stdout.reconfigure(encoding='utf-8')
K, NSIM, SEED = 5, 5000, 20261012


def icc_anova(groups):
    k = len(groups[0]); n = len(groups)
    grand = sum(map(sum, groups)) / (n * k)
    msb = k * sum((sum(g) / k - grand) ** 2 for g in groups) / (n - 1)
    msw = sum((x - sum(g) / k) ** 2 for g in groups for x in g) / (n * (k - 1))
    den = msb + (k - 1) * msw
    return (msb - msw) / den if den > 0 else 0.0


def sim_groups(rnd, p, icc, n):
    s = 1 / icc - 1  # alpha + beta
    a, b = p * s, (1 - p) * s
    out = []
    for _ in range(n):
        pi = rnd.betavariate(a, b)
        out.append([1 if rnd.random() < pi else 0 for _ in range(K)])
    return out


def test(S, models, center, rnd):
    tasks = sorted(next(iter(S.values())))
    obs = {m: icc_anova([S[m][t] for t in tasks]) for m in models}
    p1 = {m: mean(x for t in tasks for x in S[m][t]) for m in models}
    c = center(list(obs.values()))
    v_obs = pvariance(list(obs.values()))
    vs = []
    for _ in range(NSIM):
        vs.append(pvariance([icc_anova(sim_groups(rnd, p1[m], c, len(tasks))) for m in models]))
    vs.sort()
    return {'icc': {m: round(obs[m], 4) for m in models}, 'pass1': {m: round(p1[m], 4) for m in models},
            'icc_center': round(c, 4), 'V_obs': round(v_obs, 5), 'V_null_median': round(vs[NSIM // 2], 5),
            'V_null_p95': round(vs[int(0.95 * NSIM)], 5), 'p': sum(1 for v in vs if v >= v_obs) / NSIM}


def main(path):
    S = defaultdict(lambda: defaultdict(list))
    for r in csv.DictReader(open(path, encoding='utf-8')):
        S[r['model']][r['task']].append(1 if float(r['reward'] or 0) >= 1 else 0)
    rnd = random.Random(SEED)
    allm = sorted(S)
    strong = [m for m in allm if mean(x for t in S[m] for x in S[m][t]) >= 0.13]
    out = {'main_mean_center': test(S, allm, mean, rnd),
           'robust_median_center': test(S, allm, median, rnd),
           'robust_drop_weakest': dict(test(S, strong, mean, rnd), models=strong)}
    print(json.dumps(out, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main(sys.argv[1])
