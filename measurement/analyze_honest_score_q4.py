"""Q4: does accounting for retries (pass^k) change the model ranking compared with pass@1?

Computes per-model pass@1, unbiased pass^3 and pass^5 (n=5 attempts per task), the rankings by
pass@1 and pass^5, and every model pair whose order flips between pass@1 and pass^k (k = 3, 5),
with task-bootstrap 95% CIs for both differences. Hypotheses and criteria were fixed before the analysis.

Input: tb40_trials.csv (Terminal-Bench 4.0 per-trial results, columns model, task, reward;
regenerated by measurement/fetch_tb40_trials.py). Output: JSON on stdout.
Backs docs/measurements/08_defects_and_icc_tb40.md.

    python measurement/analyze_honest_score_q4.py tb40_trials.csv > measurement/honest_score_q4.json
"""
import sys, csv, json, random
from collections import defaultdict

sys.stdout.reconfigure(encoding='utf-8')
SEED, B = 20261012, 2000


def load(path):
    s = defaultdict(lambda: defaultdict(list))
    for r in csv.DictReader(open(path, encoding='utf-8')):
        s[r['model']][r['task']].append(1 if float(r['reward'] or 0) >= 1 else 0)
    return s


def p1(m, ts):
    return sum(sum(m[t]) for t in ts) / (5 * len(ts))


def pk(m, ts, k):
    # unbiased pass^k for n=5: C(c,k)/C(5,k), averaged over tasks
    from math import comb
    return sum(comb(sum(m[t]), k) / comb(5, k) for t in ts) / len(ts)


def ci(f, ts, rnd):
    v = sorted(f([rnd.choice(ts) for _ in ts]) for _ in range(B))
    return v[int(0.025 * B)], v[int(0.975 * B) - 1]


def main(path):
    S = load(path); rnd = random.Random(SEED)
    models = sorted(S); tasks = sorted(next(iter(S.values())))
    per = {m: {'pass@1': round(p1(S[m], tasks), 4), 'pass^3': round(pk(S[m], tasks, 3), 4), 'pass^5': round(pk(S[m], tasks, 5), 4),
               'ratio_pass5_to_pass1': round(pk(S[m], tasks, 5) / p1(S[m], tasks), 3)} for m in models}
    pairs = []
    for i, a in enumerate(models):
        for b in models[i + 1:]:
            d1 = p1(S[a], tasks) - p1(S[b], tasks)
            for k in (3, 5):
                dk = pk(S[a], tasks, k) - pk(S[b], tasks, k)
                if d1 * dk < 0:
                    lo, hi = ci(lambda ts: pk(S[a], ts, k) - pk(S[b], ts, k), tasks, rnd)
                    lo1, hi1 = ci(lambda ts: p1(S[a], ts) - p1(S[b], ts), tasks, rnd)
                    pairs.append({'a': a, 'b': b, 'k': k, 'diff_pass1': round(d1, 4), 'diff_passk': round(dk, 4),
                                  'passk_ci95': [round(lo, 4), round(hi, 4)], 'pass1_ci95': [round(lo1, 4), round(hi1, 4)],
                                  'passk_significant': lo > 0 or hi < 0, 'pass1_significant': lo1 > 0 or hi1 < 0})
    out = {'per_model': per,
           'rank_pass1': sorted(models, key=lambda m: -per[m]['pass@1']),
           'rank_pass5': sorted(models, key=lambda m: -per[m]['pass^5']),
           'reversed_pairs': pairs,
           'verdict_repeats_change_ranking': any(p['passk_significant'] and p['k'] == 5 for p in pairs)}
    print(json.dumps(out, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main(sys.argv[1])
